import { readFileSync } from "node:fs";

const readJson = (name) => JSON.parse(readFileSync(new URL(`../src/i18n/${name}.json`, import.meta.url), "utf8"));
const locales = readJson("locales").filter((locale) => locale.publicationStatus === "published");
const routes = readJson("routes");
// The six published destinations are the old Notura publication contract.
const destinations = ["home", "product", "howItWorks", "features", "privacy", "terms"];
export const noturaRedirects = [{ source: "/notura/", destination: "https://getnotura.com/" },
  ...locales.flatMap((locale) => destinations.flatMap((destination) => {
    const suffix = routes[destination].path;
    const path = `/${locale.urlPrefix}/${suffix ? `${suffix}/` : ""}`;
    return [`/notura${path}`, path].map((source) => ({ source, destination: `https://getnotura.com${path}` }));
  })),
];

export const redirectRules = noturaRedirects.flatMap(({ source, destination }) =>
  [source, source.slice(0, -1)].map((from) => `${from} ${destination} 301`),
);

export const redirectsText = `# Generated by scripts/generate-redirects.mjs; edit locale/route config instead.\n${redirectRules.join("\n")}\n`;
